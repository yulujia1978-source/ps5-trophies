from pathlib import Path
root=Path(__file__).resolve().parents[1]
files=[('index.html','text/html; charset=utf-8'),('app.js','text/javascript; charset=utf-8'),('model.js','text/javascript; charset=utf-8'),('style.css','text/css; charset=utf-8')]
out=['/* Generated by tools/embed.py */','typedef struct {const char *path,*type; const unsigned char *data; unsigned long size;} Asset;']
for i,(name,mime) in enumerate(files):
 data=(root/'web'/name).read_bytes()
 out.append(f'static const unsigned char asset_{i}[]={{'+','.join(map(str,data))+'};')
out.append('static const Asset assets[]={')
for i,(name,mime) in enumerate(files):out.append(f'{{"/{name}","{mime}",asset_{i},sizeof(asset_{i})}},')
out.append('};')
(root/'payload'/'assets.h').write_text('\n'.join(out))
